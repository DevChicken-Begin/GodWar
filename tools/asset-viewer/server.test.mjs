import test from 'node:test';
import assert from 'node:assert/strict';
import { createAssetServer } from './server.mjs';

await test('local viewer serves source data, candidates, and handles missing routes', async (t) => {
  const server = createAssetServer();
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  t.after(() => new Promise(resolve => server.close(resolve)));
  const origin = `http://127.0.0.1:${server.address().port}`;
  const page = await fetch(origin); assert.equal(page.status, 200); assert.match(await page.text(), /Kiểm thử hoạt ảnh/);
  const renderer = await fetch(`${origin}/render-frame.mjs`);
  assert.equal(renderer.status, 200); assert.match(renderer.headers.get('content-type'), /javascript/);
  const timing = await fetch(`${origin}/timing.mjs`);
  assert.equal(timing.status, 200); assert.match(timing.headers.get('content-type'), /javascript/);
  const catalog = await fetch(`${origin}/Asset/Character/extracted/catalog.json`);
  assert.equal(catalog.status, 200);
  const data = await catalog.json(); assert.ok(data.assets.length > 0);
  const visible = await (await fetch(`${origin}/api/assets`)).json();
  const visibleIds = new Set(visible.assets.map(item => item.id));
  for (const id of ['athen', 'scot', 'slowdame', 'kong', 'trike', 'wavyin', '3 char', 'skylian', 'wothem', 'snicore', 'lois', 'maono', 'knigblack', 'monsterdead', 'newwomen', 'firer', 'kapicon']) {
    assert.ok(!visibleIds.has(id));
    assert.equal(data.assets.some(item => item.id === id), id === '3 char');
  }
  assert.ok(visibleIds.has('wukongchen'));
  const asset = data.assets[0];
  const gif = await fetch(`${origin}/${asset.source.split('/').map(encodeURIComponent).join('/')}`);
  assert.equal(gif.status, 200); assert.equal(gif.headers.get('content-type'), 'image/gif');
  const atlas = await fetch(`${origin}/Asset/Character/extracted/${encodeURIComponent(asset.id)}/atlas_000.png`, { method: 'HEAD' });
  assert.equal(atlas.status, 200); assert.equal(atlas.headers.get('content-type'), 'image/png');
  assert.ok(Array.isArray(await (await fetch(`${origin}/api/candidates`)).json()));
  const refined = await (await fetch(`${origin}/api/refined-candidates`)).json();
  assert.ok(refined.includes('3 char'));
  assert.ok(refined.includes('Kahn'));
  assert.ok((await (await fetch(`${origin}/api/cleanup-candidates`)).json()).includes('aminao'));
  assert.ok((await (await fetch(`${origin}/api/batch-candidates`)).json()).includes('firemen'));
  assert.ok((await (await fetch(`${origin}/api/special-candidates`)).json()).includes('omra'));
  assert.ok(!(await (await fetch(`${origin}/api/temporal-candidates`)).json()).includes('athen'));
  const detailed = await (await fetch(`${origin}/api/detailed-candidates`)).json();
  for (const id of ['animent', 'artemis', 'fireknight', 'javis', 'mainthen', 'mortafi', 'overight', 'powerdame', 'scatra', 'scorpit', 'skypit', 'waven', 'wuchen', 'ziggist']) assert.ok(detailed.includes(id));
  assert.ok(!detailed.includes('morexem'));
  const foot = await (await fetch(`${origin}/api/foot-candidates`)).json();
  for (const id of ['mainthen', 'animent', 'overight', 'skypit']) assert.ok(foot.includes(id));
  assert.equal((await fetch(`${origin}/Asset/Character/foot_candidates/animent/atlas_000.png`, { method: 'HEAD' })).status, 200);
  const sceneDetail = await (await fetch(`${origin}/api/scene-detail-candidates`)).json();
  for (const id of ['animent', 'overight', 'skypit']) assert.ok(sceneDetail.includes(id));
  assert.equal((await fetch(`${origin}/Asset/Character/scene_detail_v3_candidates/skypit/atlas_000.png`, { method: 'HEAD' })).status, 200);
  const remaining = await (await fetch(`${origin}/api/remaining-scene-candidates`)).json();
  for (const id of ['animent', 'overight', 'skypit']) assert.ok(remaining.includes(id));
  assert.equal((await fetch(`${origin}/Asset/Character/remaining_scene_candidates/skypit/atlas_000.png`, { method: 'HEAD' })).status, 200);
  const spots = await (await fetch(`${origin}/api/spot-candidates`)).json();
  for (const id of ['animent', 'overight', 'skypit']) assert.ok(spots.includes(id));
  assert.equal((await fetch(`${origin}/Asset/Character/spot_candidates/skypit/atlas_000.png`, { method: 'HEAD' })).status, 200);
  assert.ok(visibleIds.has('aonoma'));
  assert.ok((await (await fetch(`${origin}/api/pixel-candidates`)).json()).includes('aonoma'));
  assert.equal((await fetch(`${origin}/Asset/Character/pixel_candidates/aonoma/atlas_000.png`, { method: 'HEAD' })).status, 200);
  assert.ok((await (await fetch(`${origin}/api/pixel-120-candidates`)).json()).includes('aonoma'));
  assert.ok((await (await fetch(`${origin}/api/pixel-180-candidates`)).json()).includes('aonoma'));
  assert.ok((await (await fetch(`${origin}/api/pixel-220-candidates`)).json()).includes('aonoma'));
  assert.ok((await (await fetch(`${origin}/api/sharp-candidates`)).json()).includes('dragonmout'));
  assert.ok((await (await fetch(`${origin}/api/scorpit-repair18-candidates`)).json()).includes('scorpit'));
  const fine = await (await fetch(`${origin}/api/fine-candidates`)).json();
  for (const id of ['agon', 'airpot', 'amore', 'aoda']) assert.ok(fine.includes(id));
  const motion = await (await fetch(`${origin}/api/motion-v2-candidates`)).json();
  assert.ok(motion.includes('blacktiger'));
  assert.ok(!motion.includes('firer'));
  const repairedV5 = await (await fetch(`${origin}/api/repaired-v5-candidates`)).json();
  assert.ok(repairedV5.includes('conden'));
  const repairedV2 = await (await fetch(`${origin}/api/repaired-v2-candidates`)).json();
  assert.ok(repairedV2.includes('conden'));
  const repaired = await (await fetch(`${origin}/api/repaired-candidates`)).json();
  for (const name of ['moxie', 'conden']) assert.ok(repaired.includes(name));
  assert.ok(!repaired.includes('newwomen'));
  assert.equal((await fetch(`${origin}/Asset/Character/repaired_candidates/moxie/candidate.json`)).status, 200);
  const fireDeep = await (await fetch(`${origin}/api/fire-deep-candidates`)).json();
  assert.ok(fireDeep.includes('fireknight'));
  const fireOrphans = await (await fetch(`${origin}/api/fire-orphan-candidates`)).json();
  assert.ok(fireOrphans.includes('fireknight'));
  assert.equal((await fetch(`${origin}/Asset/Character/fire_orphan_candidates/fireknight/atlas_000.png`, { method: 'HEAD' })).status, 200);
  const fireSpecks = await (await fetch(`${origin}/api/fire-speck-candidates`)).json();
  assert.ok(fireSpecks.includes('fireknight'));
  assert.equal((await fetch(`${origin}/Asset/Character/fire_speck_candidates/fireknight/atlas_000.png`, { method: 'HEAD' })).status, 200);
  const detail130 = await (await fetch(`${origin}/api/detail-130-candidates`)).json();
  for (const id of ['artemis', 'nox', 'overight', 'powerdame', 'wuchen', 'ziggist', 'scorpit', 'skyles', 'snowpie', 'tigerknight', 'azza', 'dracian', 'dragonmout', 'mortafi']) assert.ok(detail130.includes(id));
  assert.equal((await fetch(`${origin}/Asset/Character/fine_candidates/agon/atlas_000.png`, { method: 'HEAD' })).status, 200);
  const native = await (await fetch(`${origin}/api/native-candidates`)).json();
  for (const id of ['reptalian', 'dracian', 'vargost', 'xinchan', 'raptilian']) { assert.ok(visibleIds.has(id)); assert.ok(native.includes(id)); }
  for (const id of ['changlie', 'choptian', 'costmic', 'ractalo', 'kungchang', 'rep']) { assert.ok(visibleIds.has(id)); assert.ok(native.includes(id)); }
  for (const id of ['biden', 'airpot', 'black', 'pigpor', 'jaik']) { assert.ok(visibleIds.has(id)); assert.ok(native.includes(id)); }
  const detailOct29 = await (await fetch(`${origin}/api/detail-oct29-candidates`)).json();
  for (const id of ['dragonot', 'momo', 'nox', 'warrioram']) assert.ok(detailOct29.includes(id));
  assert.equal((await fetch(`${origin}/Asset/Character/detail_oct29_candidates/nox/frame_000.png`, { method: 'HEAD' })).status, 200);
  const pilot = await fetch(`${origin}/Asset/Character/forge_pilots/dragonot_reference_v1/godot_export/godot/preview.json`);
  assert.equal(pilot.status, 200);
  assert.equal((await pilot.json()).frames.length, 49);
  const logos = await (await fetch(`${origin}/api/logo-candidates`)).json();
  for (const id of ['airpot', 'wavinges']) assert.ok(logos.includes(id));
  assert.ok(!(await (await fetch(`${origin}/api/scene-protected-candidates`)).json()).includes('knigblack'));
  assert.equal((await fetch(`${origin}/Asset/Character/extracted/extra-preview-catalog.json`)).status, 404);
  assert.ok(visibleIds.has('changlie'));
  const local = await (await fetch(`${origin}/api/oct28-fix-candidates`)).json();
  for (const id of ['animent', 'scorpit']) assert.ok(local.includes(id));
  assert.ok((await (await fetch(`${origin}/api/scorpit-repair-candidates`)).json()).includes('scorpit'));
  assert.equal((await fetch(`${origin}/Asset/Character/scorpit_repair_candidates/scorpit/atlas_000.png`, { method: 'HEAD' })).status, 200);
  assert.equal((await fetch(`${origin}/Asset/Character/detailed_candidates/fireknight/atlas_000.png`, { method: 'HEAD' })).status, 200);
  assert.equal((await fetch(`${origin}/Asset/Character/review/background-review-status.json`)).status, 200);
  assert.equal((await fetch(`${origin}/Asset/Character/refined_candidates/3%20char/atlas_000.png`, { method: 'HEAD' })).status, 200);
  const splits = await (await fetch(`${origin}/Asset/Character/characters/3-char-splits.json`)).json();
  assert.deepEqual(splits.characters.map(item => [item.id, item.first_source_frame, item.last_source_frame]), [['solist', 0, 51], ['namero', 52, 101], ['kukaomni', 102, 155]]);
  const splitCatalog = await (await fetch(`${origin}/Asset/Character/extracted/split-catalog.json`)).json();
  assert.deepEqual(splitCatalog.assets.map(item => item.frame_count), [52, 50, 54]);
  assert.equal((await fetch(`${origin}/Asset/Character/extracted/missing.png`)).status, 404);
  assert.equal((await fetch(`${origin}/package.json`)).status, 404);
  assert.equal((await fetch(origin, { method: 'POST' })).status, 405);
});
